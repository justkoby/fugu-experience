/**
 * Non-destructive SVG extraction.
 *
 * Reads `logo-with landmark.svg` (never modified) and writes
 * `src/assets/logoSource.ts`: every <path> in original document (paint) order
 * with its CSS class fill resolved to a literal colour, plus the gradient defs.
 * All coordinates stay in the original 1080 x 1080 viewBox.
 */
import {readFileSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const svg = readFileSync(resolve(root, 'logo-with landmark.svg'), 'utf8');

const classFill = {};
for (const m of svg.matchAll(/\.(st\d+)\s*\{\s*fill:\s*([^;}\s]+)/g)) classFill[m[1]] = m[2];

const paths = [];
for (const m of svg.matchAll(/<path\b([^>]*?)\/>/g)) {
  const attrs = m[1];
  const cls = /class="([^"]+)"/.exec(attrs)?.[1];
  const d = /\sd="([^"]+)"/.exec(attrs)?.[1];
  if (!d) throw new Error('Path without d: ' + attrs.slice(0, 80));
  // A path with no class inherits the SVG default fill (black).
  const fill = cls ? classFill[cls] : '#000';
  if (!fill) throw new Error('No fill for class ' + cls);
  paths.push({id: paths.length, fill, d});
}

const gradients = [...svg.matchAll(/<linearGradient[\s\S]*?<\/linearGradient>/g)].map((m) => m[0].replace(/\s*\n\s*/g, ''));
const viewBox = /viewBox="([^"]+)"/.exec(svg)[1];

const out = `/* AUTO-GENERATED by scripts/extract-svg.mjs from "logo-with landmark.svg" — do not edit. */
export type SourcePath = {readonly id: number; readonly fill: string; readonly d: string};

export const SOURCE_VIEWBOX = ${JSON.stringify(viewBox)};

export const SOURCE_GRADIENTS = ${JSON.stringify(gradients.join(''))};

export const SOURCE_PATHS: readonly SourcePath[] = ${JSON.stringify(paths, null, 0).replace(/\},\{/g, '},\n{')};
`;
writeFileSync(resolve(root, 'src/assets/logoSource.ts'), out);
console.log(`Extracted ${paths.length} paths, ${gradients.length} gradient(s) → src/assets/logoSource.ts`);
